"""
Ask - grounded question answering over the attribution results.

Every answer is assembled from EVIDENCE items (E1, E2, ...) that come straight
from the service: attribution results, the validation report, the method
config/spec and the gate. The answer text cites them as [E#].

Before an answer is returned, every number in it is checked against the
numbers in its evidence (`verify_numbers`). Nothing is generated by a model,
so the same question always gets the same answer.
"""
from __future__ import annotations

import math
import re
from collections import defaultdict
from statistics import mean
from typing import Callable

# ----------------------------------------------------------------------------- formatting
MINUS = "−"


def pct(x: float, d: int = 1, sign: bool = True) -> str:
    s = f"{abs(x) * 100:.{d}f}%"
    if not sign:
        return s
    return ("+" if x > 0 else MINUS if x < 0 else "") + s


def money(x: float) -> str:
    a, s = abs(x), (MINUS if x < 0 else "")
    if a >= 1e6:
        return f"{s}${a / 1e6:.2f}M"
    if a >= 1e3:
        return f"{s}${a / 1e3:.1f}k"
    return f"{s}${a:.0f}"


def _half_up(x: float, d: int = 0) -> float:
    # match the dashboard (JavaScript) rounding: .5 always rounds away from zero
    return math.floor(abs(x) * 10 ** d + 0.5) / 10 ** d


def units(x: float, sign: bool = True) -> str:
    s = f"{_half_up(x):,.0f}"
    return (("+" if x > 0 else MINUS if x < 0 else "") + s) if sign else s


# ----------------------------------------------------------------------------- evidence
class Evidence:
    def __init__(self):
        self.items: list[dict] = []

    def add(self, kind: str, title: str, source: str, data: dict) -> str:
        eid = f"E{len(self.items) + 1}"
        self.items.append({"id": eid, "kind": kind, "title": title, "source": source, "data": data})
        return eid


PROMO_FIELDS = ("promo_id", "promo_name", "category", "mechanic", "discount_pct", "start_week", "end_week",
                "duration_weeks", "uplift_pct", "ci_low", "ci_high", "confidence_level", "p_value", "verdict",
                "actual_units", "counterfactual_units", "incremental_units", "incremental_units_low",
                "incremental_units_high", "incremental_revenue", "incremental_margin", "funding_cost", "roi",
                "avg_promo_price",
                "pre_period_mape", "control_strategy")


def promo_evidence(ev: Evidence, r: dict) -> str:
    data = {k: r.get(k) for k in PROMO_FIELDS}
    data["n_treated_stores"] = len(r.get("treated_stores", []))
    data["n_control_stores"] = len(r.get("control_stores", []))
    data["n_baseline_weeks"] = len(r.get("baseline_weeks", []))
    data["spreadsheet_pre_post"] = r["naive_estimates"]["pre_post_no_control"]
    data["promoted_vs_unpromoted"] = r["naive_estimates"]["promoted_vs_unpromoted_stores"]
    src = f"attribution result · method v{r['method_version']} · config {r['config_hash']} · data {r['data_hash']}"
    return ev.add("promotion", f"{r['promo_id']} · {r['promo_name']}", src, data)


# ----------------------------------------------------------------------------- number verification
_NUM = re.compile(r"(?P<sign>[-+−])?(?P<cur>\$)?(?P<num>\d[\d,]*(?:\.\d+)?)(?P<unit>\s?(?:%|pp|k\b|M\b))?")
_DATE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b")
_SKIP = [re.compile(p) for p in (r"\[E\d+\]", r"\b[PSK]\d{2,3}\b", r"\bv?\d+\.\d+\.\d+\b", r"(?m)^\s*\d+\.\s",
                                  r"Poisson\(1\)", r"SHA-256", r"\b\d+(?:st|nd|rd|th)\b", r"\b[0-9a-f]{12,16}\b", r"\bB[1-5]\b|\bV[1-4]\b|\bG[1-5]\b|\bE\d+\b")]


def _evidence_numbers(obj, out: list[float]) -> None:
    if isinstance(obj, bool) or obj is None:
        return
    if isinstance(obj, (int, float)):
        out.append(float(obj))
    elif isinstance(obj, str):
        for m in re.finditer(r"\d[\d,]*(?:\.\d+)?", obj):
            out.append(float(m.group().replace(",", "")))
    elif isinstance(obj, dict):
        for v in obj.values():
            _evidence_numbers(v, out)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            _evidence_numbers(v, out)


def _evidence_strings(obj, out: list[str]) -> None:
    if isinstance(obj, str):
        out.append(obj)
    elif isinstance(obj, dict):
        for v in obj.values():
            _evidence_strings(v, out)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            _evidence_strings(v, out)


def verify_numbers(text: str, evidence: list[dict]) -> dict:
    """Every number in `text` must match a number in the evidence (after % / k / M scaling and rounding)."""
    nums: list[float] = []
    strings: list[str] = []
    for e in evidence:
        _evidence_numbers(e["data"], nums)
        _evidence_strings(e["data"], strings)
    blob = " ".join(strings)
    checks = []
    for d in _DATE.findall(text):
        checks.append({"text": d, "verified": d in blob})
    clean = _DATE.sub(" ", text)
    for p in _SKIP:
        clean = p.sub(" ", clean)
    for m in _NUM.finditer(clean):
        raw, unit = m.group().strip(), (m.group("unit") or "").strip()
        num_s = m.group("num").replace(",", "")
        v = float(num_s)
        dec = len(num_s.split(".")[1]) if "." in num_s else 0
        scale = {"k": 1e3, "M": 1e6}.get(unit, 1.0)
        tol = 0.5 * 10 ** (-dec) * scale * 1.0001 + 1e-9
        target = v * scale
        cands = [abs(x) for x in nums]
        if unit in ("%", "pp"):
            cands = cands + [abs(x) * 100 for x in nums]
        ok = any(abs(c - target) <= tol for c in cands)
        checks.append({"text": raw, "verified": ok})
    return {"checked": len(checks), "verified": sum(c["verified"] for c in checks),
            "all_verified": all(c["verified"] for c in checks), "numbers": checks}


# ----------------------------------------------------------------------------- language helpers
STOP = set("""the a an of for in on to and or is was were did do does how what which who with by its it this that
these those about our we me show tell give vs versus compare between best worst top average overall promo promos
promotion promotions perform performed performance doing work works worked are be been has have had much many
there their they them than more most less least off deal deals sale sales store stores price i you can could would
should please why when where explain list all any per each week weeks result results number numbers did
""".split())
DEFINITIONAL = re.compile(r"comput|calculat|defin|chosen|choose|select|work|method|explain|mean|what is|what are")
PRONOUN = re.compile(r"\b(its|it|this one|that one|this|that|those|them|they|their)\b|\bwhat about\b|\band (the )?(roi|uplift|revenue)\b")
METRICS = {
    "roi": r"\broi\b|return on|profit|pay(s|ed)? (back|off)|worth it|money",
    "uplift": r"uplift|\blift\b|impact|effect|increase|grow",
    "revenue": r"revenue|sales value|\$|dollar",
    "units": r"\bunits?\b|volume|incremental units",
    "margin": r"margin",
    "ci": r"confiden|interval|\brange\b|how sure|uncertain|error bar|margin of error",
    "significance": r"significan|p-value|p value|\breal\b|chance|noise",
    "controls": r"control|twin|matched|comparison stores|compared (with|to|against)",
    "baseline": r"baseline|normal weeks|pre-period|pre period",
    "spreadsheet": r"spreadsheet|naive|pre/post|pre-post|old method",
    "truth": r"planted|ground truth|true effect|truth|actual effect",
}
RANK_METRIC = {"roi": "roi", "revenue": "incremental_revenue", "units": "incremental_units",
               "margin": "incremental_margin", "uplift": "uplift_pct"}
METRIC_LABEL = {"roi": "ROI", "incremental_revenue": "incremental revenue", "incremental_units": "incremental units",
                "incremental_margin": "incremental margin", "uplift_pct": "uplift"}


def _fmt_metric(key: str, v: float) -> str:
    if key in ("roi",):
        return pct(v, 0)
    if key == "uplift_pct":
        return pct(v)
    if key in ("incremental_revenue", "incremental_margin"):
        return money(v)
    return units(v)


def _metric(q: str) -> str | None:
    for k, pat in METRICS.items():
        if re.search(pat, q):
            return k
    return None


def _tokens(s: str) -> list[str]:
    out = []
    for w in re.findall(r"[a-z][a-z\-]+", s.lower()):
        for part in w.split("-"):
            if len(part) >= 3 and part not in STOP:
                out.append(part[:-1] if part.endswith("s") and len(part) > 4 else part)
    return out


# ----------------------------------------------------------------------------- the engine
class AskEngine:
    def __init__(self, results: list[dict], cfg: dict, method_md: str,
                 validation: Callable[[], dict], calibration: dict | None, gate: Callable[[], list[dict]]):
        self.results = {r["promo_id"]: r for r in results}
        self.ok = [r for r in results if r["status"] == "ok"]
        self.cfg = cfg
        self.method_sections = self._sections(method_md or "")
        self.validation = validation
        self.calibration = calibration
        self.gate = gate

    @staticmethod
    def _sections(md: str) -> dict[int, dict]:
        out = {}
        for m in re.finditer(r"^## (\d+)\. ([^\n]+)\n(.*?)(?=^## |\Z)", md, re.S | re.M):
            out[int(m.group(1))] = {"title": m.group(2).strip(), "text": m.group(3).strip()}
        return out

    # ---- entity resolution --------------------------------------------------
    def find_promos(self, q: str) -> list[str]:
        ids = [f"P{int(n):02d}" for n in re.findall(r"\b(?:p|pr-?0*)(\d{1,2})\b", q, re.I)]
        ids = [i for i in dict.fromkeys(ids) if i in self.results]
        if ids:
            return ids
        qt = set(_tokens(q))
        if not qt:
            return []
        scores = {}
        for pid, r in self.results.items():
            name = set(_tokens(r["promo_name"]))
            meta = set(_tokens(f"{r['category']} {r['mechanic']}"))
            if r["mechanic"] == "BOGO":
                meta |= {"bogo", "buy", "one", "get"}
            s = 2 * len(qt & name) + len(qt & meta)
            if s:
                scores[pid] = s
        if not scores:
            return []
        best = max(scores.values())
        return [p for p, s in scores.items() if s == best]

    # ---- dispatcher -----------------------------------------------------------
    def answer(self, question: str, context: dict | None = None) -> dict:
        q = question.strip()
        ql = q.lower()
        ctx_ids = [p for p in (context or {}).get("promo_ids", []) if p in self.results]
        ev = Evidence()
        trace = [f"question: {q!r}"]
        explicit = [f"P{int(n):02d}" for n in re.findall(r"\b(?:p|pr-?0*)(\d{1,2})\b", q, re.I)]

        if not q:
            intent, text, ids = "empty", "Ask about a promotion, a ranking, or the method.", []
        elif explicit and any(i in self.results for i in explicit):
            ids = self.find_promos(q)
            intent, text = ("compare", self._compare(ids, ev)) if len(ids) > 1 else ("promotion", self._promo(ids[0], ql, ev))
        elif re.search(r"planted|ground truth|recover|accura|tolerance|validat|how (good|reliable|trustworthy)|can (we|i) trust", ql):
            intent, text, ids = "validation", self._validation(ev), []
        elif re.search(r"\bgate\b|proposal|method change|blocked|\bmerge|\bci\b pipeline", ql):
            intent, text, ids = "gate", self._gate(ev), []
        elif re.search(r"overall|summary|portfolio|how did (the |our )?promotions|how are (the |our )?promotions|all promotions", ql):
            intent, text, ids = "portfolio", self._portfolio(ev), []
        elif ctx_ids and not re.search(r"\btop\b|\brank|on average|which promotions", ql) and (
                PRONOUN.search(ql) or re.search(r"\bwe\b", ql) or (_metric(ql) and not DEFINITIONAL.search(ql))):
            ids = ctx_ids
            trace.append(f"follow-up: resolved pronoun to {', '.join(ids)} from conversation context")
            intent, text = ("compare", self._compare(ids, ev, _metric(ql))) if len(ids) > 1 else ("promotion", self._promo(ids[0], ql, ev))
        elif re.search(r"on average|\baverage\b|by (mechanic|category|type)|which (mechanic|category|type|event)|event types?|kind of promo|types? of promo", ql):
            intent, text, ids = "group", self._group(ql, ev), []
        elif re.search(r"\btop\b|\bbest\b|\bworst\b|highest|lowest|\brank|biggest|smallest|\bmost\b|\bleast\b|bottom", ql):
            intent, text, ids = "ranking", self._ranking(ql, ev), []
        elif re.search(r"lost money|lose money|unprofitable|negative roi|not profitable|no (measurable )?effect|not significant|didn.?t work|declin|hurt|negative|which .*significant|profitable|made money", ql):
            intent, text, ids = "list", self._list(ql, ev), []
        elif self._method_topic(ql) is not None and not self.find_promos(q):
            intent, ids = "method", []
            text = self._method(self._method_topic(ql), ev)
        elif (ids := self.find_promos(q)):
            trace.append(f"matched promotion name to {', '.join(ids)}")
            intent, text = ("compare", self._compare(ids, ev, _metric(ql))) if len(ids) > 1 else ("promotion", self._promo(ids[0], ql, ev))
        elif re.search(r"\bpromo(tion)?s?\b", ql) and re.search(r"how did|perform|\bdo\b|\bdid\b|result", ql):
            intent, ids = "not_found", []
            names = [f"{r['promo_id']} {r['promo_name']}" for r in self.results.values()]
            e = ev.add("query", "Promotion catalogue", "promotions.csv", {"promotions": names})
            words = ", ".join(f"'{w}'" for w in _tokens(q)) or "that"
            text = (f"I couldn't find a promotion matching {words}. The promotions in this data set are [{e}]: {', '.join(names)}. "
                    f"Ask by ID or by a word from the name, such as \"the chocolate promotion\".")
        else:
            intent, ids = "fallback", []
            text = ("I couldn't match that to a promotion, ranking or method topic. I can answer questions about "
                    "**a single promotion** (by ID, or by name like \"the chocolate promotion\"), **rankings** by uplift, ROI or "
                    "revenue, **averages by mechanic or category**, **the method** (baseline, control stores, confidence "
                    "interval) and **validation** against the planted effects. Try one of the suggestions below.")
        trace.insert(1, f"intent: {intent}")
        if ids:
            trace.append(f"promotions: {', '.join(ids)}")
        trace.append(f"evidence items: {len(ev.items)}")
        ver = verify_numbers(text, ev.items)
        trace.append(f"number check: {ver['verified']}/{ver['checked']} numbers found in evidence")
        if not ver["all_verified"]:
            bad = ", ".join(c["text"] for c in ver["numbers"] if not c["verified"])
            text += f"\n\n> ⚠ Some numbers could not be matched to the evidence ({bad}). Treat them with caution."
        return {"question": q, "intent": intent, "answer": text, "evidence": ev.items, "verification": ver,
                "trace": trace, "context": {"promo_ids": ids or ctx_ids},
                "method_version": self.cfg["method_version"], "suggestions": self._suggest(intent, ids)}

    # ---- intents ------------------------------------------------------------------
    def _verdict_sentence(self, r: dict) -> str:
        if r["ci_low"] > 0:
            return "a **significant uplift**: the whole interval is above zero"
        if r["ci_high"] < 0:
            return "a **significant decline**: the whole interval is below zero"
        return "**no measurable effect**: the interval includes zero, so it cannot be told apart from no change"

    def _promo(self, pid: str, ql: str, ev: Evidence) -> str:
        r = self.results[pid]
        if r["status"] != "ok":
            e = ev.add("promotion", f"{pid} · {r['promo_name']}", "attribution result", {"status": r["status"], "reason": r.get("reason")})
            return f"The method **refused** to attribute {pid} [{e}]: {r.get('reason')}."
        e = promo_evidence(ev, r)
        head = f"**{pid} · {r['promo_name']}**"
        m = _metric(ql)
        conf = round(r["confidence_level"] * 100)
        if m == "roi":
            return (f"{head} had an ROI of **{pct(r['roi'], 0)}** [{e}]: incremental margin {money(r['incremental_margin'])} "
                    f"against a funding cost of {money(r['funding_cost'])} [{e}].\n\n"
                    f"ROI = (incremental margin − funding cost) ÷ funding cost. "
                    + ("It paid back." if r["roi"] > 0 else
                       "It did not pay back" + (" because the deep discount makes each extra unit loss-making." if r["incremental_margin"] < 0 else
                                                 " because the extra margin was smaller than the funding cost.")))
        if m == "revenue":
            return (f"{head} generated **{money(r['incremental_revenue'])}** of incremental revenue [{e}]: "
                    f"{units(r['incremental_units'])} incremental units at an average promo price of "
                    f"${r['avg_promo_price']:.2f} [{e}].")
        if m == "units":
            return (f"{head} sold **{units(r['incremental_units'])} incremental units** [{e}] "
                    f"({conf}% CI {units(r['incremental_units_low'])} to {units(r['incremental_units_high'])}) [{e}]. "
                    f"Actual sales were {units(r['actual_units'], False)} units against a counterfactual of "
                    f"{units(r['counterfactual_units'], False)} [{e}].")
        if m in ("ci", "significance"):
            return (f"{head}: uplift **{pct(r['uplift_pct'])}**, {conf}% confidence interval **{pct(r['ci_low'])} to "
                    f"{pct(r['ci_high'])}** [{e}], p-value {r['p_value']:.3f} [{e}]. That is {self._verdict_sentence(r)}.")
        if m == "controls":
            ctrl = r["control_stores"][:6]
            e2 = ev.add("controls", f"{pid} control stores", "attribution result",
                        {"n_control_stores": len(r["control_stores"]), "n_treated_stores": len(r["treated_stores"]),
                         "pre_period_mape": r["pre_period_mape"], "candidates": r["control_candidates"],
                         "controls_per_treated": self.cfg["controls"]["controls_per_treated"],
                         "examples": [c["store_id"] for c in ctrl]})
            return (f"{head} was measured against **{len(r['control_stores'])} control stores** chosen for its "
                    f"{len(r['treated_stores'])} treated stores, out of {r['control_candidates']} untreated candidates [{e2}]. "
                    f"Each treated store gets the {self.cfg['controls']['controls_per_treated']} closest stores of the same format and region [{e2}]. Before launch the "
                    f"counterfactual tracked actual sales within {pct(r['pre_period_mape'], 1, False)} on average [{e2}].")
        if m == "baseline":
            excl = r["excluded_weeks"]
            e2 = ev.add("baseline", f"{pid} baseline weeks", "attribution result",
                        {"baseline_weeks": r["baseline_weeks"], "excluded_weeks": excl})
            return (f"{head} used **{len(r['baseline_weeks'])} baseline weeks**, {r['baseline_weeks'][0]} to "
                    f"{r['baseline_weeks'][-1]} [{e2}]. "
                    + (f"{len(excl)} week(s) were excluded: " + "; ".join(f"{x['week']} ({x['reason']})" for x in excl) + f" [{e2}]."
                       if excl else "No weeks needed to be excluded."))
        if m == "spreadsheet":
            return (f"For {head} the method says **{pct(r['uplift_pct'])}** [{e}]. A pre/post spreadsheet would have said "
                    f"{pct(r['naive_estimates']['pre_post_no_control'])}, and comparing promoted with unpromoted stores "
                    f"{pct(r['naive_estimates']['promoted_vs_unpromoted_stores'])} [{e}]. Both shortcuts ignore seasonality "
                    f"and the fact that promoted stores are bigger.")
        disc = f", {round(r['discount_pct'] * 100)}% off" if r["discount_pct"] else ""
        return (f"{head} ({r['mechanic']}{disc}, {r['start_week']} to {r['end_week']}) delivered an uplift of "
                f"**{pct(r['uplift_pct'])}** [{e}], with a {conf}% confidence interval of {pct(r['ci_low'])} to "
                f"{pct(r['ci_high'])} [{e}]. That is {self._verdict_sentence(r)}.\n\n"
                f"- **Incremental units:** {units(r['incremental_units'])} (CI {units(r['incremental_units_low'])} to "
                f"{units(r['incremental_units_high'])}) [{e}]\n"
                f"- **Incremental revenue:** {money(r['incremental_revenue'])} [{e}]\n"
                f"- **ROI:** {pct(r['roi'], 0)} after a {money(r['funding_cost'])} funding cost [{e}]\n"
                f"- **Counterfactual:** built from {len(r['control_stores'])} matched control stores for "
                f"{len(r['treated_stores'])} treated stores [{e}]")

    def _compare(self, ids: list[str], ev: Evidence, metric: str | None = None) -> str:
        rows = [self.results[i] for i in ids if self.results[i]["status"] == "ok"]
        lines = [f"Comparing {len(rows)} promotions:\n"]
        for r in rows:
            e = promo_evidence(ev, r)
            lines.append(f"- **{r['promo_id']} · {r['promo_name']}**: uplift {pct(r['uplift_pct'])} "
                         f"(CI {pct(r['ci_low'])} to {pct(r['ci_high'])}), ROI {pct(r['roi'], 0)}, "
                         f"incremental revenue {money(r['incremental_revenue'])} [{e}]")
        key = RANK_METRIC.get(metric or "uplift", "uplift_pct")
        best = max(rows, key=lambda r: r[key])
        lines.append(f"\n**{best['promo_id']}** comes out ahead on {METRIC_LABEL[key]}.")
        overlap = len(rows) == 2 and not (rows[0]["ci_high"] < rows[1]["ci_low"] or rows[1]["ci_high"] < rows[0]["ci_low"])
        if overlap and key == "uplift_pct":
            lines.append(" Their confidence intervals overlap, so the uplift difference is not clear-cut.")
        return "\n".join(lines)

    def _ranking(self, ql: str, ev: Evidence) -> str:
        m = _metric(ql)
        key = RANK_METRIC.get(m or "uplift", "uplift_pct")
        n_m = re.search(r"\b(?:top|bottom|best|worst)\s+(\d{1,2})\b|\b(\d{1,2})\s+(?:best|worst|top|promo)", ql)
        n = int(next(g for g in n_m.groups() if g)) if n_m else 5
        asc = bool(re.search(r"worst|lowest|bottom|least|smallest", ql))
        year = re.search(r"\b(20\d\d)\b", ql)
        mech = [x for x in ("tpr", "bogo", "display", "bundle", "loyalty") if re.search(rf"\b{x}\b", ql)]
        rows = [r for r in self.ok if (not year or r["start_week"].startswith(year.group(1)))
                and (not mech or r["mechanic"].lower() in mech)]
        rows = sorted(rows, key=lambda r: r[key], reverse=not asc)[:n]
        filt = []
        if year:
            filt.append(f"starting in {year.group(1)}")
        if mech:
            filt.append(f"mechanic {', '.join(x.upper() for x in mech)}")
        q = ev.add("query", "Ranking query", "derived from attribution results",
                   {"metric": key, "n_requested": n, "n_returned": len(rows), "year": int(year.group(1)) if year else None})
        if not rows:
            return f"No promotions match that filter [{q}]."
        head = (f"{'Bottom' if asc else 'Top'} {len(rows)} promotions by **{METRIC_LABEL[key]}**"
                + (f" ({'; '.join(filt)})" if filt else "") + f" [{q}]:\n")
        lines = [head]
        for i, r in enumerate(rows, 1):
            e = promo_evidence(ev, r)
            extra = f", uplift {pct(r['uplift_pct'])}" if key != "uplift_pct" else f", CI {pct(r['ci_low'])} to {pct(r['ci_high'])}"
            lines.append(f"{i}. **{r['promo_id']} · {r['promo_name']}**: {METRIC_LABEL[key]} {_fmt_metric(key, r[key])}{extra} [{e}]")
        if key == "roi" and any(r["roi"] < 0 for r in rows) and not asc:
            lines.append("\nNote: some promotions in this list still lost money (negative ROI).")
        return "\n".join(lines)

    def _group(self, ql: str, ev: Evidence) -> str:
        dim = "category" if re.search(r"categor", ql) else "mechanic"
        groups = defaultdict(list)
        for r in self.ok:
            groups[r[dim]].append(r)
        stats = []
        for g, rows in groups.items():
            stats.append({"group": g, "n": len(rows), "promo_ids": [r["promo_id"] for r in rows],
                          "mean_uplift_pct": round(mean(r["uplift_pct"] for r in rows), 6),
                          "mean_roi": round(mean(r["roi"] for r in rows), 6),
                          "total_incremental_revenue": round(sum(r["incremental_revenue"] for r in rows), 2)})
        by = "mean_roi" if _metric(ql) == "roi" else "mean_uplift_pct"
        stats.sort(key=lambda s: s[by], reverse=True)
        lines = [f"Average results by **{dim}**, sorted by {'ROI' if by == 'mean_roi' else 'uplift'}:\n"]
        for s in stats:
            e = ev.add("group", f"{dim}: {s['group']}", "aggregate of attribution results", s)
            lines.append(f"- **{s['group']}** ({s['n']} promo{'s' if s['n'] > 1 else ''}: {', '.join(s['promo_ids'])}): "
                         f"average uplift {pct(s['mean_uplift_pct'])}, average ROI {pct(s['mean_roi'], 0)} [{e}]")
        top_u = max(stats, key=lambda s: s["mean_uplift_pct"])
        top_r = max(stats, key=lambda s: s["mean_roi"])
        lines.append(f"\n**{top_u['group']}** drives the most volume; **{top_r['group']}** is the most profitable."
                     if top_u["group"] != top_r["group"] else f"\n**{top_u['group']}** leads on both volume and profit.")
        lines.append(" These are averages over a handful of promotions: each promotion's uplift is measured causally, "
                     "but the comparison between groups is descriptive.")
        return "\n".join(lines)

    def _list(self, ql: str, ev: Evidence) -> str:
        if re.search(r"lost money|lose money|unprofitable|negative roi|not profitable", ql):
            rows, title = [r for r in self.ok if r["roi"] < 0], "lost money (negative ROI)"
        elif re.search(r"profitable|made money", ql):
            rows, title = [r for r in self.ok if r["roi"] > 0], "paid back (positive ROI)"
        elif re.search(r"no (measurable )?effect|not significant|didn.?t work", ql):
            rows, title = [r for r in self.ok if r["ci_low"] <= 0 <= r["ci_high"]], "had no measurable effect"
        elif re.search(r"declin|hurt|negative", ql):
            rows, title = [r for r in self.ok if r["ci_high"] < 0], "significantly reduced sales"
        else:
            rows, title = [r for r in self.ok if r["ci_low"] > 0], "had a significant uplift"
        q = ev.add("query", "Filter query", "derived from attribution results",
                   {"filter": title, "n_matching": len(rows), "n_total": len(self.ok)})
        if not rows:
            return f"No promotions {title} [{q}]."
        lines = [f"**{len(rows)} of {len(self.ok)}** promotions {title} [{q}]:\n"]
        for r in rows:
            e = promo_evidence(ev, r)
            lines.append(f"- **{r['promo_id']} · {r['promo_name']}**: uplift {pct(r['uplift_pct'])} "
                         f"(CI {pct(r['ci_low'])} to {pct(r['ci_high'])}), ROI {pct(r['roi'], 0)} [{e}]")
        return "\n".join(lines)

    def _portfolio(self, ev: Evidence) -> str:
        up = [r for r in self.ok if r["ci_low"] > 0]
        down = [r for r in self.ok if r["ci_high"] < 0]
        roi_pos = [r for r in self.ok if r["roi"] > 0]
        data = {"n_promotions": len(self.ok), "n_significant_uplift": len(up), "n_significant_decline": len(down),
                "n_no_effect": len(self.ok) - len(up) - len(down), "n_roi_positive": len(roi_pos),
                "total_incremental_revenue": round(sum(r["incremental_revenue"] for r in self.ok), 2)}
        e = ev.add("portfolio", "Portfolio summary", f"attribution results · method v{self.cfg['method_version']}", data)
        return (f"Across **{data['n_promotions']} promotions** [{e}]: {data['n_significant_uplift']} had a significant uplift, "
                f"{data['n_no_effect']} had no measurable effect and {data['n_significant_decline']} significantly reduced sales [{e}]. "
                f"Together they added {money(data['total_incremental_revenue'])} of incremental revenue, but only "
                f"{data['n_roi_positive']} paid back their funding cost [{e}].")

    def _validation(self, ev: Evidence) -> str:
        rep = self.validation()
        s = rep["summary"]
        e = ev.add("validation", "Recovery of planted effects (reference data)", "validation report", s)
        txt = (f"Yes. On the reference data the method recovered **{s['n_passed']} of {s['n_promos']}** planted effects within "
               f"±{s['tolerance_pp']}pp [{e}]. The largest error was {s['max_abs_error_pp']:.2f}pp and the average "
               f"{s['mean_abs_error_pp']:.2f}pp [{e}], and {pct(s['ci_coverage'], 0, False)} of the confidence intervals "
               f"contained the true effect [{e}]. The zero-effect promotion was "
               f"{'correctly **not** called significant' if s['V2_nulls_not_significant'] else 'wrongly called significant'} [{e}].")
        c = self.calibration
        if c:
            e2 = ev.add("calibration", f"Calibration across {c['seeds']} synthetic worlds", "reports/tolerance_calibration.json",
                        {k: c[k] for k in ("seeds", "estimates", "tolerance_pp", "abs_error_pp", "share_within_tolerance",
                                           "mean_ci_coverage", "null_false_positive_rate")})
            txt += (f"\n\nTo check this wasn't luck, the world was regenerated {c['seeds']} times ({c['estimates']} estimates): "
                    f"{pct(c['share_within_tolerance'], 1, False)} landed within ±{c['tolerance_pp']}pp, with a "
                    f"99th-percentile error of {c['abs_error_pp']['p99']}pp [{e2}].")
        return txt

    def _gate(self, ev: Evidence) -> str:
        reps = self.gate()
        n_block = sum(g["verdict"] == "BLOCK" for g in reps)
        q = ev.add("query", "Gate runs", "configs/proposals/*.yaml",
                   {"n_proposals": len(reps), "n_pass": len(reps) - n_block, "n_block": n_block})
        lines = [f"There are **{len(reps)} proposed method changes** [{q}]; **{n_block}** were blocked by the gate [{q}]:\n"]
        for g in reps:
            g1 = next(c for c in g["checks"] if c["id"] == "G1")
            e = ev.add("gate", g["label"], f"gate · v{g['current_version']} -> v{g['proposed_version']}",
                       {"verdict": g["verdict"], "n_passed": g["recovery"]["summary"]["n_passed"],
                        "n_promos": g["recovery"]["summary"]["n_promos"],
                        "max_abs_error_pp": g["recovery"]["summary"]["max_abs_error_pp"]})
            lines.append(f"- **{g['label']}**: **{g['verdict']}**, {g['recovery']['summary']['n_passed']}/"
                         f"{g['recovery']['summary']['n_promos']} recovered, max error "
                         f"{g['recovery']['summary']['max_abs_error_pp']:.2f}pp [{e}]")
        lines.append("\nA BLOCK means the change cannot merge: it no longer recovers the hidden answers within tolerance.")
        return "\n".join(lines)

